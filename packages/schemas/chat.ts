import { CHAT_ALLOWED_FILE_TYPES, CHAT_MAX_FILE_SIZE } from '@repo/constants';
import { z } from 'zod';

/** Schemas for chat */
export const chatSchema = {
  /** Schema for the file upload request */
  uploadInput: z.object({
    /** Original file name */
    fileName: z.string().min(1),
    /** MIME type of the file */
    fileType: z.enum(CHAT_ALLOWED_FILE_TYPES),
    /** File size in bytes */
    fileSize: z.number().int().positive().max(CHAT_MAX_FILE_SIZE),
  }),

  /** Schema for message feedback */
  feedback: z.object({
    /** The message ID to submit feedback for */
    messageId: z.string(),
    /** Thumbs up or down */
    rating: z.enum(['up', 'down']),
    /** Optional comment about how the response could be improved */
    comment: z.string().max(1000).optional(),
  }),

  /** Schema for message metadata — flows through the stream and persists with the message */
  messageMetadata: z.object({
    traceId: z.string().optional(),
    feedback: z.boolean().optional(),
    /** True if this assistant message was stopped by the user mid-stream. */
    cancelled: z.boolean().optional(),
  }),

  /** Data parts the chat stream sends alongside the response (keyed by name, sent as `data-<name>`) */
  dataParts: {
    /**
     * A new conversation's AI-generated title. It's generated alongside the response and sent as
     * soon as it's ready, so the sidebar can show it without waiting for the response to finish.
     */
    'conversation-title': z.object({ title: z.string() }),
  },

  /** Schema for cancelling a chat — `partial` is the assistant message the user saw before stopping */
  cancel: z.object({
    partial: z
      .object({
        id: z.string(),
        parts: z.array(z.object({ type: z.string() }).passthrough()),
      })
      .optional(),
  }),

  /** Schema for sending a message — only the new user message; the server owns the history */
  chatMessage: z.object({
    /** The conversation ID (generated by the client; the conversation is created on first send) */
    id: z.string().min(1),
    /** The user message to answer. Re-sending a saved message regenerates its response */
    message: z.object({
      id: z.string().min(1),
      role: z.literal('user'),
      parts: z.array(z.object({ type: z.string() }).passthrough()),
    }),
  }),
};
